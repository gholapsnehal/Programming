def Add(No1, No2):

    Result = No1 + No2

    return Result

def Sub(No1,No2):

    Result = No1 - No2

    return Result

def Mult(No1, No2):

    Result = No1 * No2

    return Result

def Div(No1, No2):

    Result = No1 / No2

    return Result