import schedule
import time

##################################################################################################
#
# Function Name : Display
# Input         : None
# Output        : None
# Description   : Display reminder message on console
# Date          : 21/07/2026
#
##################################################################################################

def Display():

    print("Coding kar...!")

##################################################################################################
#
# Function Name : main
# Input         : None
# Output        : None
# Description   : Call Display function immediately and then
#                 schedule it after every 30 minutes
# Date          : 21/07/2026
#
##################################################################################################

def main():

    schedule.every(30).minutes.do(Display)

    while True:
        schedule.run_pending()
        time.sleep(1)

##################################################################################################
#
#   Starter of Application
#
##################################################################################################

if __name__ == "__main__":
    main()