import schedule
import time

##################################################################################################
#
# Function Name : Display
# Input         : None
# Output        : None
# Description   : Display greeting message on console
# Date          : 21/07/2026
#
##################################################################################################

def Display():

    print("Namskar...")

##################################################################################################
#
# Function Name : main
# Input         : None
# Output        : None
# Description   : Schedule Display function daily at 09:00 AM that prints Namskar
# Date          : 21/07/2026
#
##################################################################################################

def main():

    schedule.every().day.at("09:00").do(Display)

    while True:
        schedule.run_pending()
        time.sleep(5)

##################################################################################################
#
#   Starter of Application
#
##################################################################################################

if __name__ == "__main__":
    main()